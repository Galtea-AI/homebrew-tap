#!/usr/bin/env bash
# Writes one formula for one release. Used for Formula/galtea.rb (the
# newest release) and for each Formula/galtea@<major>.<minor>.rb.
#
#   render-formula.sh <output.rb> <formula name> <tag> <checksums.txt> <owner/repo> [conflicting formula ...]
set -euo pipefail

OUT="$1" NAME="$2" TAG="$3" CHECKSUMS="$4" OWNER_REPO="$5"
shift 5
VERSION="${TAG#v}"
BASE_URL="https://github.com/${OWNER_REPO}/releases/download/${TAG}"

# Homebrew derives the class from the file name: galtea@5.4 -> GalteaAT54.
CLASS=$(echo "$NAME" | sed -e 's/@/AT/' -e 's/\.//g' -e 's/^g/G/')

sha() {
  local sum
  sum=$(awk -v pat="galtea_${VERSION}_$1.tar.gz" '$2 == pat { print $1; exit }' "$CHECKSUMS")
  if [ -z "$sum" ]; then
    echo "::error::No checksum for galtea_${VERSION}_$1.tar.gz in $CHECKSUMS" >&2
    exit 1
  fi
  echo "$sum"
}
SHA_DARWIN_AMD64=$(sha darwin_amd64)
SHA_DARWIN_ARM64=$(sha darwin_arm64)
SHA_LINUX_AMD64=$(sha linux_amd64)
SHA_LINUX_ARM64=$(sha linux_arm64)

# Every formula installs the same `galtea` binary, so each one conflicts
# with all the others.
CONFLICTS=""
for other in "$@"; do
  CONFLICTS+="  conflicts_with \"${other}\", because: \"both install a \`galtea\` binary\""$'\n'
done
[ -z "$CONFLICTS" ] || CONFLICTS+=$'\n'

cat > "$OUT" <<RUBY
# typed: false
# frozen_string_literal: true

# This file is generated by .github/workflows/sync.yml. DO NOT EDIT.
class ${CLASS} < Formula
  desc "Galtea CLI - terminal-native client for the Galtea AI testing & evaluation platform"
  homepage "https://galtea.ai"
  version "${VERSION}"
  license "Apache-2.0"

${CONFLICTS}  on_macos do
    if Hardware::CPU.intel?
      url "${BASE_URL}/galtea_${VERSION}_darwin_amd64.tar.gz"
      sha256 "${SHA_DARWIN_AMD64}"

      def install
        bin.install "galtea"
      end
    end
    if Hardware::CPU.arm?
      url "${BASE_URL}/galtea_${VERSION}_darwin_arm64.tar.gz"
      sha256 "${SHA_DARWIN_ARM64}"

      def install
        bin.install "galtea"
      end
    end
  end

  on_linux do
    if Hardware::CPU.intel? && Hardware::CPU.is_64_bit?
      url "${BASE_URL}/galtea_${VERSION}_linux_amd64.tar.gz"
      sha256 "${SHA_LINUX_AMD64}"

      def install
        bin.install "galtea"
      end
    end
    if Hardware::CPU.arm? && Hardware::CPU.is_64_bit?
      url "${BASE_URL}/galtea_${VERSION}_linux_arm64.tar.gz"
      sha256 "${SHA_LINUX_ARM64}"

      def install
        bin.install "galtea"
      end
    end
  end

  test do
    system "#{bin}/galtea", "--version"
  end
end
RUBY
